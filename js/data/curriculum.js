function getDay(n) {
  return curriculum.find(d => d.day === n) || null;
}

// Cumulative letters unlocked by the end of a given day.
function lettersUnlockedBy(dayNum) {
  const set = new Set();
  curriculum.filter(d => d.day <= dayNum).forEach(d => d.letterIdx.forEach(i => set.add(i)));
  return set;
}
